def approved_policy(
    source_key: str = SOURCE_KEY,
    permissions: Optional[Mapping[ReuseDimension, ReusePermission]] = None,
    acquisition_mode: AcquisitionMode = AcquisitionMode.OFFICIAL_API,
) -> SourcePolicyRegistry:
    """A registry approving one synthetic source. Never the real registry."""
    matrix = permissions or {d: ReusePermission.ALLOWED for d in ReuseDimension}
    record_ = SourcePolicyRecord(
        source_key=source_key,
        display_name="Fixture source (synthetic, not a real scientific source)",
        role=SourceRole.SUPPORTING_ANNOTATION,
        status=SourcePolicyStatus.APPROVED,
        acquisition_mode=acquisition_mode,
        version_policy="fixture: pinned by the test",
        citation_policy="fixture: cited as a fixture",
        license_identifier="FIXTURE-NOT-A-REAL-LICENCE",
        reuse=ReuseMatrix(matrix),
        permitted_claim_categories=(ClaimCategory.SUPPORTING_ANNOTATION,),
        evidence=(SourceEvidenceReference(
            evidence_type=EvidenceType.OFFICIAL_TERMS_PAGE,
            official_url=FIXTURE_TERMS_URL,
            retrieved_at=NOW,
            content_hash=sha256_digest({"fixture": "terms"}),
            summary="Synthetic fixture terms.",
            verification=EvidenceVerificationStatus.VERIFIED),),
        review=ReviewRecord(
            decision=ReviewDecision.APPROVE,
            reviewer_name=TEST_SCIENTIFIC_REVIEWER,
            reviewer_role="synthetic fixture reviewer",
            decided_at=NOW,
            evidence_urls=(FIXTURE_TERMS_URL,)))
    return SourcePolicyRegistry(records=(record_,))


def pending_policy(source_key: str = SOURCE_KEY) -> SourcePolicyRegistry:
    """A registry that registers the source and approves nothing."""
    return SourcePolicyRegistry(records=(SourcePolicyRecord(
        source_key=source_key,
        display_name="Fixture pending source (synthetic)",
        role=SourceRole.SUPPORTING_ANNOTATION),))
