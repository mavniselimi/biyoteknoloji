"""The curation record and its parts (WP-09).

Standard library plus :mod:`pgx.domain` only. Nothing here touches a database,
a filesystem or a network, and nothing here creates a persisted
:class:`pgx.domain.models.CuratedInterpretation`: WP-09 defines the contract
that stage must satisfy, and WP-10 owns the workflow that fills it in.

The shape of this module is one idea repeated. A source said something; a
curator concluded something; those are two objects, and no field belongs to
both. Every place the two could touch is a place a source's word could become
this project's claim, so each is spelled out and each is refused.
"""

