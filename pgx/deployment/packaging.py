# -*- coding: utf-8 -*-
"""Lockfile and distribution builds (WP-24).

Two operations, and a rule that governs both: **nothing here writes a result
it did not obtain.**

``uv.lock`` is generated by ``uv``, from ``pyproject.toml``, against a real
package index. It is never written by this module, never templated, never
approximated from installed versions, and never carried over from another
project. A lockfile that was not resolved is not a lockfile - it is a list of
versions that happen to be written down, and the one thing a lockfile is for
is being the versions a resolver agreed on.

The distribution build runs the declared PEP 517 backend twice, from two
separate clean staging directories, and compares the artifact hashes.
``SOURCE_DATE_EPOCH`` is pinned across both runs, because a zip archive
records mtimes and two builds a second apart otherwise differ in bytes while
being identical in content - which would report irreproducibility that is not
there and, worse, would train whoever reads the report to ignore it.

When the index is unreachable, or the backend is not importable, the result is
``BLOCKED`` with the reason. That is a truthful measurement of this host and
is not a failure of the software.
"""

from __future__ import annotations

import hashlib
import os
import shutil
import subprocess  # noqa: S404 - building this project is the point
import tempfile
from typing import Mapping, Optional, Sequence, Tuple

from pgx.deployment.vocabulary import ExecutionState, blocker

__all__ = [
    "LOCKFILE_NAME",
    "SOURCE_DATE_EPOCH",
    "build_distributions_twice",
    "lock_dependencies",
    "verify_lockfile",
]

LOCKFILE_NAME = "uv.lock"

#: A fixed, deliberately unremarkable instant used for both builds so that
#: archive metadata cannot make two identical builds look different. Chosen
#: rather than "now" precisely because "now" differs between the two runs.
SOURCE_DATE_EPOCH = "1735689600"  # 2025-01-01T00:00:00Z

#: What is copied into a clean staging directory for a build. Everything a
#: source distribution declares plus the metadata the backend reads. Nothing
#: else - a build that could see ``.venv`` or ``data/`` would produce a
#: different artifact depending on what happened to be lying around.
STAGED_FOR_BUILD: Tuple[str, ...] = (
    "pyproject.toml", "README.md", "alembic.ini",
    "pgx", "apps", "migrations", "config", "schemas",
)

_BUILD_TIMEOUT_SECONDS = 600


def _run(argv: Sequence[str], *, cwd: Optional[str] = None,
         env: Optional[Mapping[str, str]] = None,
         timeout: int = 120) -> Tuple[int, str]:
    try:
        completed = subprocess.run(  # noqa: S603 - fixed argv, no shell
            list(argv), cwd=cwd, capture_output=True, text=True,
            timeout=timeout, check=False,
            env=dict(os.environ, **dict(env or {})))
    except FileNotFoundError:
        return 127, "%s is not installed" % argv[0]
    except subprocess.TimeoutExpired:
        return 124, "timed out after %ds" % timeout
    output = ((completed.stdout or "") + (completed.stderr or "")).strip()
    return completed.returncode, output[-2000:]


def _sha256(path: str) -> str:
    digest = hashlib.sha256()
    with open(path, "rb") as handle:
        for chunk in iter(lambda: handle.read(65536), b""):
            digest.update(chunk)
    return "sha256:" + digest.hexdigest()


# ---------------------------------------------------------------------------
# Lockfile
# ---------------------------------------------------------------------------

def lock_dependencies(root: str = ".", *, runner=None) -> Mapping[str, object]:
    """Resolve ``pyproject.toml`` into ``uv.lock``. One attempt.

    One attempt on purpose. An index that refused once will refuse again, and
    a retry loop turns a clear BLOCKED into a slow one while producing the
    same answer.
    """
    run = runner or _run
    lock_path = os.path.join(root, LOCKFILE_NAME)
    if shutil.which("uv") is None:
        return _lock_result(
            ExecutionState.BLOCKED, root,
            blocker_code="DEPLOY_PACKAGE_INDEX_UNAVAILABLE",
            owner="the build environment",
            detail="uv is not installed, so no resolution can be attempted")
    code, output = run(["uv", "lock", "--project", root], timeout=300)
    if code != 0:
        return _lock_result(
            ExecutionState.BLOCKED, root,
            blocker_code="DEPLOY_PACKAGE_INDEX_UNAVAILABLE",
            owner="the build environment",
            detail=("uv lock exited %d; no lockfile was written. The file is "
                    "never hand-written or approximated: a set of versions "
                    "no resolver agreed on is not a lockfile. Output: %s"
                    % (code, output.splitlines()[-1] if output else "none")))
    if not os.path.isfile(lock_path):  # pragma: no cover - uv wrote nothing
        return _lock_result(
            ExecutionState.BLOCKED, root,
            blocker_code="DEPLOY_LOCKFILE_ABSENT",
            owner="the build environment",
            detail="uv reported success but wrote no lockfile")
    return _lock_result(ExecutionState.EXECUTED, root)


def verify_lockfile(root: str = ".", *, runner=None) -> Mapping[str, object]:
    """Frozen check: does the lockfile still match ``pyproject.toml``?

    ``uv lock --check`` exits non-zero when the two disagree. That is the
    check CI runs, and it is the one that catches a dependency added to
    ``pyproject.toml`` without relocking - which otherwise ships an image
    built from versions the lockfile does not describe.
    """
    run = runner or _run
    lock_path = os.path.join(root, LOCKFILE_NAME)
    if not os.path.isfile(lock_path):
        return _lock_result(
            ExecutionState.BLOCKED, root,
            blocker_code="DEPLOY_LOCKFILE_ABSENT",
            owner="the build environment",
            detail="no uv.lock exists, so there is nothing to verify")
    if shutil.which("uv") is None:
        return _lock_result(
            ExecutionState.BLOCKED, root,
            blocker_code="DEPLOY_LOCKFILE_UNVERIFIED",
            owner="the build environment",
            detail="uv is not installed, so the frozen check cannot run")
    code, output = run(["uv", "lock", "--check", "--project", root],
                       timeout=180)
    if code != 0:
        return _lock_result(
            ExecutionState.BLOCKED, root,
            blocker_code="DEPLOY_LOCKFILE_UNVERIFIED",
            owner="whoever changed pyproject.toml",
            detail=("uv lock --check exited %d: the lockfile does not match "
                    "pyproject.toml" % code))
    return _lock_result(ExecutionState.VERIFIED, root)


def _lock_result(state: ExecutionState, root: str, *,
                 blocker_code: Optional[str] = None,
                 owner: str = "", detail: str = "") -> Mapping[str, object]:
    lock_path = os.path.join(root, LOCKFILE_NAME)
    present = os.path.isfile(lock_path)
    return {
        "lockfile_name": LOCKFILE_NAME,
        "lockfile_present": present,
        "lockfile_sha256": _sha256(lock_path) if present else None,
        "state": state.value,
        "blockers": ([dict(blocker(blocker_code, owner=owner,
                                   detail=detail).to_json())]
                     if blocker_code else []),
        "note": (
            "uv.lock is produced by uv against a real index or it does not "
            "exist. It is never hand-written, never approximated from "
            "installed versions, and never copied from elsewhere."),
    }


