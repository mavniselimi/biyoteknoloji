# Distributions
# ---------------------------------------------------------------------------

def _stage(root: str, destination: str) -> None:
    """Copy the declared build inputs into a clean directory.

    Copied rather than built in place so that the two builds cannot share a
    ``build/`` directory, a ``.egg-info`` or a cached wheel - each of which
    would make the second build agree with the first for the wrong reason.
    """
    for name in STAGED_FOR_BUILD:
        source = os.path.join(root, name)
        target = os.path.join(destination, name)
        if os.path.isdir(source):
            shutil.copytree(
                source, target,
                ignore=shutil.ignore_patterns("__pycache__", "*.pyc"))
        elif os.path.isfile(source):
            shutil.copy2(source, target)


def _build_once(root: str, *, runner=None) -> Mapping[str, object]:
    run = runner or _run
    staging = tempfile.mkdtemp(prefix="pgx-wp24-build-")
    try:
        _stage(root, staging)
        output_dir = os.path.join(staging, "dist")
        code, text = run(
            [os.environ.get("PYTHON", "python3"), "-m", "build",
             "--outdir", output_dir, staging],
            cwd=staging,
            env={"SOURCE_DATE_EPOCH": SOURCE_DATE_EPOCH,
                 "PYTHONHASHSEED": "0"},
            timeout=_BUILD_TIMEOUT_SECONDS)
        if code != 0:
            return {"ok": False, "detail": text.splitlines()[-1] if text
                    else "build exited %d" % code}
        artifacts = {}
        for name in sorted(os.listdir(output_dir)):
            path = os.path.join(output_dir, name)
            if name.endswith(".whl"):
                artifacts["wheel"] = {"name": name, "sha256": _sha256(path)}
            elif name.endswith(".tar.gz"):
                artifacts["sdist"] = {"name": name, "sha256": _sha256(path)}
        return {"ok": True, "artifacts": artifacts}
    finally:
        shutil.rmtree(staging, ignore_errors=True)


def build_distributions_twice(root: str = ".", *,
                              runner=None) -> Mapping[str, object]:
    """Build a wheel and an sdist twice, and compare the hashes.

    The comparison is the measurement. Two hashes that agree are evidence the
    build is reproducible *on this host, at this moment* - it is not evidence
    that it is reproducible on a different platform, and this report does not
    say that it is.
    """
    import importlib.util

    missing = [name for name in ("hatchling", "build")
               if importlib.util.find_spec(name) is None]
    if missing:
        return {
            "state": ExecutionState.BLOCKED.value,
            "reproducible": None,
            "builds": [],
            "blockers": [dict(blocker(
                "DEPLOY_BUILD_BACKEND_UNAVAILABLE",
                owner="the build environment",
                detail=("%s not importable here, so no distribution can be "
                        "produced with the declared backend. Substituting a "
                        "different backend would build a different artifact "
                        "than any deployment installs."
                        % ", ".join(sorted(missing)))).to_json())],
            "source_date_epoch": SOURCE_DATE_EPOCH,
            "note": _BUILD_NOTE,
        }
    first = _build_once(root, runner=runner)
    if not first.get("ok"):
        return {"state": ExecutionState.NOT_EXECUTED.value,
                "reproducible": None, "builds": [first],
                "blockers": [], "source_date_epoch": SOURCE_DATE_EPOCH,
                "note": _BUILD_NOTE}
    second = _build_once(root, runner=runner)
    if not second.get("ok"):
        return {"state": ExecutionState.NOT_EXECUTED.value,
                "reproducible": None, "builds": [first, second],
                "blockers": [], "source_date_epoch": SOURCE_DATE_EPOCH,
                "note": _BUILD_NOTE}
    left = first["artifacts"]  # type: ignore[index]
    right = second["artifacts"]  # type: ignore[index]
    comparisons = {}
    for kind in ("wheel", "sdist"):
        comparisons[kind] = {
            "first": left.get(kind), "second": right.get(kind),
            "identical": (left.get(kind) or {}).get("sha256")
            == (right.get(kind) or {}).get("sha256")
            and left.get(kind) is not None,
        }
    reproducible = all(item["identical"] for item in comparisons.values())
    return {
        "state": (ExecutionState.VERIFIED.value if reproducible
                  else ExecutionState.EXECUTED.value),
        "reproducible": reproducible,
        "comparisons": comparisons,
        "builds": [first, second],
        "blockers": [],
        "source_date_epoch": SOURCE_DATE_EPOCH,
        "note": _BUILD_NOTE,
    }


_BUILD_NOTE = (
    "Two builds from two clean staging directories with SOURCE_DATE_EPOCH "
    "pinned. Agreement is evidence of reproducibility on this host at this "
    "moment; it is not evidence of reproducibility across platforms, and this "
    "document does not claim that.")
